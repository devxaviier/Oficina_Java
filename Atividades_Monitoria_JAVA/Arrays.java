package ExerciciosArray;

public class Arrays {
    public static void main(String[] args) {
        int[] notas = new int[3];
        notas[0] = 7;
        notas[1] = 7;
        notas[2] = 7;

        String[] nomes = {"Ana", "Beto", "Caio"};
        double[] precos = new double[10];

        System.out.println("precos: " + precos.length);
        System.out.println("nomes: " + nomes.length);
        System.out.println("notas: " + notas.length);

    }
}
